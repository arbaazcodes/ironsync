import { test, expect } from "@playwright/test";
test("public signup, recovery and protected routes", async ({ page }) => {
  await page.goto("/onboarding", { waitUntil: "domcontentloaded" });
  await expect(page).toHaveURL(/onboarding/);
  await page.goto("/auth?mode=signup", { waitUntil: "domcontentloaded" });
  await page.getByLabel("Name", { exact: true }).fill("New Athlete");
  await page.getByLabel("Email", { exact: true }).fill("new@example.test");
  await page.getByLabel("Password", { exact: true }).fill("test-password-123");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Check your email");
  await page.goto("/auth?mode=signin", { waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: "Forgot password?" }).click();
  await page.getByLabel("Email", { exact: true }).fill("athlete@example.test");
  await page.getByRole("button", { name: "Send reset link" }).click();
  await expect(page.getByRole("status")).toContainText("password reset link");
  await page.goto("/dashboard/workout", { waitUntil: "domcontentloaded" });
  await expect(page).toHaveURL(/\/auth\?mode=signin/);
  expect((await page.request.get("/api/workouts")).status()).toBe(401);
  expect((await page.request.post("/api/coach", { data: { message: "hello" } })).status()).toBe(503);
});
test("consumer sign-in, real set persistence, offline refresh, completion and account isolation", async ({ page, browser }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/auth?mode=signin", { waitUntil: "domcontentloaded" });
  await page.getByLabel("Email", { exact: true }).fill("athlete@example.test");
  await page.getByLabel("Password", { exact: true }).fill("test-password-123");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/dashboard\/workout/);
  await page.getByRole("button", { name: "Start workout", exact: true }).click();
  await page.getByLabel("Exercise", { exact: true }).selectOption("barbell-bench-press");
  await page.getByRole("button", { name: "Add exercise", exact: true }).click();
  const weight = page.getByLabel("Barbell Bench Press set 1 weight", { exact: true });
  const reps = page.getByLabel("Barbell Bench Press set 1 reps", { exact: true });
  const done = page.getByRole("button", { name: "Barbell Bench Press set 1 complete", exact: true });
  await weight.fill("22.5"); await reps.fill("12"); await done.click();
  await expect(page.getByRole("status")).toContainText("Saved to your account");
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(weight).toHaveValue("22.5"); await expect(reps).toHaveValue("12"); await expect(done).toHaveAttribute("aria-pressed", "true");
  // Simulate failed cloud requests while the page itself remains reloadable.
  await page.route("**/api/workouts", route => route.fulfill({ status: 503, contentType: "application/json", body: '{"error":"Simulated offline cloud"}' }));
  await weight.fill("25");
  await page.reload();
  await expect(weight).toHaveValue("25");
  await expect(page.getByRole("status")).toContainText("cloud sync pending");
  await page.unroute("**/api/workouts");
  await page.getByRole("button", { name: "Sync now" }).click();
  await expect(page.getByRole("status")).toContainText("Saved to your account");
  await page.getByRole("button", { name: "Finish workout", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Workout complete", exact: true })).toBeVisible();
  await expect(page.getByRole("status")).toContainText("Saved to your account");
  await page.reload();
  await expect(page.getByText("1 sets · 12 reps · 300 kg lifted", { exact: false })).toBeVisible();
  await page.screenshot({ path: "test-results/workout-completed-mobile.png", fullPage: true });
  const history = await (await page.request.get("/api/workouts")).json();
  expect(history.sessions).toHaveLength(1);
  expect(history.sessions[0].session.status).toBe("completed");
  // A normal consumer remains blocked from the admin UI/API even if its lookup errors.
  await page.goto("/admin/members", { waitUntil: "domcontentloaded" });
  await expect(page).toHaveURL(/login\?tab=admin/);
  expect((await page.request.get("/api/admin/members")).status()).toBe(401);
  const context = await browser.newContext();
  const other = await context.newPage();
  await other.goto("/auth?mode=signin", { waitUntil: "domcontentloaded" });
  await other.getByLabel("Email", { exact: true }).fill("other@example.test");
  await other.getByLabel("Password", { exact: true }).fill("test-password-123");
  await other.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(other).toHaveURL(/dashboard\/workout/);
  await expect(other.getByRole("button", { name: "Start workout", exact: true })).toBeVisible();
  const otherHistory = await (await other.request.get("/api/workouts")).json();
  expect(otherHistory.sessions).toEqual([]);
  await context.close();
  expect(errors).toEqual([]);
});
